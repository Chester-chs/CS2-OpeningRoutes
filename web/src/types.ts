export type Mode = "desktop" | "web";
export type Side = "T" | "CT";
export type Source = {
  event: string;
  match: string;
  date: string;
  url: string;
  verified: boolean;
  reviewer: string;
};
export type Match = {
  id: string;
  map: string;
  source: Source;
  sha256: string;
  game_version: string;
  parser_version: string;
  tick_rate: number;
  route_sample_hz: number;
  players: { id: string; name: string }[];
  warnings: string[];
};
export type Teaching = Record<string, string | number | boolean> & {
  status?: string;
  title?: string;
  area?: string;
};
export type Throw = {
  id: string;
  match_id: string;
  round_id: string;
  round_number: number;
  map: string;
  player_id: string;
  player: string;
  team: string;
  side: Side;
  kind: string;
  tick: number;
  time: number;
  position: (number | null)[];
  view: { pitch: number | null; yaw: number | null };
  inventory: string[] | null;
  effect_position: (number | null)[] | null;
  effect_tick: number | null;
  trajectory: number[][];
  trajectory_status: string;
  is_pistol: boolean;
  teaching: Teaching;
  gaps: string[];
  origin_place?: string | null;
  effect_place?: string | null;
  origin_area?: string;
  effect_area?: string;
  effect_place_basis?: { method: string; distance: number } | null;
  variant_id?: string | null;
};
export type Variant = {
  id: string;
  source: "auto" | "manual";
  members: string[];
  players: string[];
  map: string;
  kind: string;
  side: Side;
  title: string;
  purpose: string;
  reviewed: boolean;
  reviewer: string;
};
export type Equipment = {
  player_id: string;
  player: string;
  team: string;
  side: Side;
  inventory: string[] | null;
  armor: number | null;
};
export type Round = {
  id: string;
  match_id: string;
  number: number;
  is_pistol: boolean;
  complete: boolean;
  winner: Side | null;
  start_tick: number;
  freeze_end_tick: number;
  end_tick: number | null;
  reason: string;
  review_required: boolean;
  pistol_basis: string;
  equipment: Equipment[];
  opening_kill: { attacker: string; victim: string; tick: number } | null;
  bomb_events: { kind: string; tick: number; player: string }[];
  review: {
    approved?: boolean;
    description?: string;
    pro_video?: string;
    reviewer?: string;
    resolution?: "" | "confirmed" | "excluded";
    resolution_note?: string;
    pistol_override?: boolean | null;
  };
  excluded?: boolean;
  resolution?: string;
};
export type Plan = {
  id: string;
  title: string;
  area: string;
  side: Side;
  purpose: string;
  conditions: string;
  status: string;
  steps: { throw_id: string; role: string; time: number; followup: string }[];
  counter_ids: string[];
  counter_explanation: string;
};
export type Catalog = {
  schema_version: number;
  matches: Match[];
  rounds: Round[];
  throws: Throw[];
  plans: Plan[];
  variants?: Variant[];
  places?: Record<string, Record<string, string>>;
};
export type Filters = {
  query?: string;
  area?: string;
  map?: string;
  side?: string;
  kind?: string;
  player?: string;
  team?: string;
  match?: string;
  dateFrom?: string;
  dateTo?: string;
  status?: string;
  result?: string;
};
export type Point = [number, number, number, number, Side, boolean];
export type Timeline = {
  round_id: string;
  tick_rate: number;
  sample_hz: number;
  point_fields: string[];
  players: Record<string, { name: string; points: Point[] }>;
};
export type Job = {
  id: string;
  status: string;
  stage: string;
  error?: string;
  created_at: string;
  source: Source;
};
